    private void btnCarregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCarregarActionPerformed
        StringBuilder dadosSessoes = new StringBuilder();
        if (txtCaminhoArquivo.getText().equals("")){
            
            JOptionPane.showMessageDialog(this,"Informe o nome do arquivo");
            txtCaminhoArquivo.requestFocus();
            
            return;
        }
        String resposta = Util.carregarArquivoEmHashMap(txtCaminhoArquivo.getText(), hashSessoes.sessoes, dadosSessoes);
        if (!resposta.equals("")){
            
            JOptionPane.showMessageDialog(this, resposta);
            txtCaminhoArquivo.setText("");
            
            return;
        }
        
        txaDados.setText(dadosSessoes.toString());
        jPanelResultados.setVisible(true);
        
        
    }//GEN-LAST:event_btnCarregarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        if (txtPesquisa.getText().equals("")){
            
            JOptionPane.showMessageDialog(this,"Número de celular não informado");
            txtPesquisa.requestFocus();
            
            return;
        }
        
        Sessao sessao = hashSessoes.sessoes.get(txtPesquisa.getText());
        if (sessao == null){
            
            JOptionPane.showMessageDialog(this,"Número de celular não encontrado");
            txtPesquisa.setText("");
            txtPesquisa.requestFocus();
            
            return;
        }
        txaResultado.setText(sessao.toString());
    }//GEN-LAST:event_btnBuscarActionPerformed

